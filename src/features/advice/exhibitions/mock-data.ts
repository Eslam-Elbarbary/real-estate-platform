function sections(
  entries: Array<[string, ...string[]]>,
): ExhibitionContentSection[] {
  return entries.map(([heading, ...paragraphs], index) => ({
    id: `section-${index + 1}`,
    heading,
    paragraphs,
  }));
}

function createExhibition(input: {
  id: string;
  slug: string;
  title: string;
  shortDescription: string;
  category: ExhibitionCategory;
  startDate: string;
  endDate?: string;
  startTime?: string;
  endTime?: string;
  locationName?: string;
  city?: string;
  venue?: string;
  organizerName?: string;
  coverImage: string;
  posterImage: string;
  featured?: boolean;
  createdAt: string;
  contentSections: ExhibitionContentSection[];
}): RealEstateExhibition {
  return {
    ...input,
    categoryLabel: exhibitionCategoryLabels[input.category],
  };
}

