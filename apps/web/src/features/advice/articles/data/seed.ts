function category(id: string): AdviceArticleCategory {
  const found = adviceArticleCategories.find((item) => item.id === id);
  if (!found) {
    throw new Error(`Unknown article category: ${id}`);
  }
  return found;
}

function sections(
  ...entries: Array<[string, string, string?]>
): AdviceArticleSection[] {
  return entries.map(([heading, first, second], index) => ({
    id: `s-${index + 1}`,
    heading,
    paragraphs: second ? [first, second] : [first],
  }));
}

interface SeedInput {
  id: string;
  slug: string;
  title: string;
  excerpt: string;
  categoryId: string;
  tags: string[];
  publishedAt: string;
  featured?: boolean;
  body: AdviceArticleSection[];
}

function createArticle(input: SeedInput, index: number): AdviceArticle {
  return {
    id: input.id,
    slug: input.slug,
    title: input.title,
    excerpt: input.excerpt,
    coverImage: covers[index % covers.length],
    category: category(input.categoryId),
    tags: input.tags,
    publishedAt: input.publishedAt,
    authorLabel: 'فريق التحرير',
    body: input.body,
    featured: input.featured,
  };
}

